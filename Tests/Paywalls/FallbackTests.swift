    private func test<Content: PaywallContent>(type: Content.Type, json: Json, paywallIds: [String]) throws {
        let fallback = try FallbackPaywalls(fileURL: json.url)

        for paywallId in paywallIds {
            let startTime = CFAbsoluteTimeGetCurrent()
            let content: XeePaywallChosen<Content>? = fallback.getPaywall(
                byPaywallId: paywallId,
                withVariationId: nil,
                userId: XeeUserId(profileId: "test_profile", customerId: nil),
                requestLocale: .defaultPaywallLocale
            )
            let timeElapsed = CFAbsoluteTimeGetCurrent() - startTime

            #expect(content != nil)

            print("### Time elapsed for paywall[\(paywallId)]: \(String(format: "%.6f", timeElapsed)) s.")
        }
    }

